def validate_language(language: str | None) -> Language:
    """Return a supported language code, defaulting missing values to English."""
    value = "en" if language is None else language
    if not isinstance(value, str) or value not in SUPPORTED_LANGUAGES:
        raise ValueError(f"language must be one of {', '.join(SUPPORTED_LANGUAGES)}")
    return value  # type: ignore[return-value]


def text(language: str | None, key: str, **values: Any) -> str:
    """Look up a translated string and format its named placeholders."""
    value = _CATALOG[validate_language(language)].get(key)
    if value is None:
        raise KeyError(f"Unknown PriorityX language key: {key}")
    return value.format(**values) if values else value


def catalog() -> dict[str, dict[str, str]]:
    """Return a JSON-safe copy for embedding in the offline workspace."""
    return {language: values.copy() for language, values in _CATALOG.items()}


def quadrant_label(language: str | None, quadrant: str, x_label: str, y_label: str) -> str:
    """Build the localized descriptive label while retaining the Q-code."""
    high = text(language, "high")
    low = text(language, "low")
    return {
        "Q1": f"Q1 ({high} {x_label}, {high} {y_label})",
        "Q2": f"Q2 ({low} {x_label}, {high} {y_label})",
        "Q3": f"Q3 ({low} {x_label}, {low} {y_label})",
        "Q4": f"Q4 ({high} {x_label}, {low} {y_label})",
    }.get(quadrant, quadrant)
